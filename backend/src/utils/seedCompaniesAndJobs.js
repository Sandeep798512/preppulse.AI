const seedCompaniesAndJobs = async () => {
  try {
    const existingCompanyCount = await Company.countDocuments();
    if (existingCompanyCount === 0) {
      console.log('⚡ Seeding initial placement companies...');
      const createdCompanies = await Company.insertMany(seedCompanies);
      console.log(`✅ Successfully seeded ${createdCompanies.length} top tech companies.`);

      const companyMap = new Map();
      createdCompanies.forEach((c) => {
        companyMap.set(c.normalizedName, c._id);
      });

      const existingJobCount = await JobOpening.countDocuments();
      if (existingJobCount === 0) {
        console.log('⚡ Seeding initial campus job openings...');
        const jobsToInsert = seedJobs.map((j) => {
          const companyId = companyMap.get(j.companyKey) || createdCompanies[0]._id;
          const { companyKey, ...jobFields } = j;
          return {
            ...jobFields,
            companyId,
          };
        });

        const createdJobs = await JobOpening.insertMany(jobsToInsert);
        console.log(`✅ Successfully seeded ${createdJobs.length} verified placement job openings.`);
      }
    }
  } catch (error) {
    console.error(`⚠️ Error seeding companies and jobs: ${error.message}`);
  }
};

module.exports = {
  seedCompaniesAndJobs,
};
