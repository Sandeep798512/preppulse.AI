/**
 * Get random question from seed bank based on filter parameters
 */
const getFallbackQuestion = (category, difficulty, excludeTexts = []) => {
  const catKey = category ? category.toLowerCase() : 'technical';
  const list = seedInterviewQuestions[catKey] || seedInterviewQuestions.technical;
  
  const excludeSet = new Set(excludeTexts);
  const available = list.filter((q) => !excludeSet.has(q.question));

  if (available.length === 0) {
    // Return any question not in excludeSet from all categories
    const all = [
      ...seedInterviewQuestions.hr,
      ...seedInterviewQuestions.technical,
      ...seedInterviewQuestions.project,
      ...seedInterviewQuestions.behavioral,
    ];
    const fallbackAvailable = all.filter((q) => !excludeSet.has(q.question));
    return fallbackAvailable.length > 0
      ? fallbackAvailable[Math.floor(Math.random() * fallbackAvailable.length)]
      : all[0];
  }

  // Prefer matching difficulty if available
  const diffMatch = available.filter(
    (q) => !difficulty || q.difficulty.toLowerCase() === difficulty.toLowerCase()
  );

  const selectedList = diffMatch.length > 0 ? diffMatch : available;
  return selectedList[Math.floor(Math.random() * selectedList.length)];
};

